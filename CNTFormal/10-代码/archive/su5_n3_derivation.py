# 构造 T₃-Y 平面上的归一化生成元
T3_unit = T3_mat / sqrt(2 * trace(T3_mat @ T3_mat).real)  # Tr=1/2 约定
Y_unit = Y_mat / sqrt(2 * trace(Y_mat @ Y_mat).real)

# 角向参数化: 在 T₃-Y 平面上的单位方向
# u(θ) = cos(2θ) T3_unit + sin(2θ) Y_unit  
# 注意: 参数为 2θ 以确保周期 π (匹配 sin(2θ) 的 ℓ=1 行为)

# ℓ=2 对称无迹算符:
# O(θ) = {u(θ), u(θ)}/2 − (1/N)·Tr(u(θ)²)/N · 1_{N×N}
# 由于 Tr(u²) = 1/2 (归一化约定):
# O(θ) = {u, u}/2 − 1/(2N) · 1

# 在 5 表示 (fundamental) 中显式计算 O(θ) 的角向分量
# O(θ) 可以展开为: A + B·cos(2θ) + C·sin(2θ) + D·cos(4θ) + E·sin(4θ)
# 提取 cos(4θ) 分量

def compute_O_theta(theta):
    """计算 ℓ=2 算符在角度 θ 的值 (5 表示)"""
    u = np.cos(2*theta) * T3_unit + np.sin(2*theta) * Y_unit
    u_sq = u @ u
    O = (u @ u + u @ u) / 2 - np.eye(N) * trace(u_sq).real / N
    return O

# 通过傅里叶分析提取 cos(4θ) 分量
n_pts = 200
thetas = np.linspace(0, np.pi/2, n_pts)
O_cos4 = np.zeros((N, N), dtype=complex)
for i, th in enumerate(thetas):
    O_th = compute_O_theta(th)
    # 对 cos(4θ) 做内积
    weight = np.cos(4*th) * (np.pi/2 / n_pts)
    # 对于 θ=0,π/2, 权重减半 (梯形法则)
    if i == 0 or i == n_pts-1:
        weight *= 0.5
    O_cos4 += O_th * weight * (4/np.pi)  # 归一化: ∫₀^{π/2} cos²(4θ) dθ = π/4

print(f"\nO(θ) 的 cos(4θ) 分量 (5 表示):")
print(f"  矩阵的 Frobenius 范数: {np.linalg.norm(O_cos4, 'fro'):.6f}")

