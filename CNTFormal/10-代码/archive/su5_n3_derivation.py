    """返回 SU(5) 生成元列表 (λ_a/2 约定, N²−1=24 个)"""
    gens = []
    # 对角 (Cartan): 4 个
    def H_diag(vals):
        """vals: [v1,...,v5], 构造对角无迹矩阵/√(2 Σ v²)"""
        vals = np.array(vals, dtype=float)
        v_sq = np.sum(vals**2)
        H = np.diag(vals).astype(complex) / sqrt(2 * v_sq)
        return H
    
    gens.append(('H1', H_diag([1, -1, 0, 0, 0])))
    gens.append(('H2', H_diag([1, 1, -2, 0, 0])))
    gens.append(('H3', H_diag([1, 1, 1, -3, 0])))
    gens.append(('H4', H_diag([1, 1, 1, 1, -4])))
    
    # 非对角: 20 个 (对称+反对称对)
    # 归一化: λ_a/2 约定, Tr(T_a T_b) = δ_{ab}/2
    # 对 S = E_{ij}+E_{ji}: Tr(S²) = 2, 所以 T = S/2 → Tr(T²) = 1/2
    for i in range(N):
        for j in range(i+1, N):
            S = np.zeros((N, N), dtype=complex)
            S[i, j] = 1; S[j, i] = 1
            S = S / 2.0  # Tr(S²) = 2 → 除以2后 Tr=1/2
            gens.append((f'S_{i}{j}', S))
            
            A = np.zeros((N, N), dtype=complex)
            A[i, j] = -1j; A[j, i] = 1j
            A = A / 2.0  # Tr(A²) = 2 → 除以2后 Tr=1/2
            gens.append((f'A_{i}{j}', A))
    return gens

